#!/usr/bin/env python3
"""Write src/jwst_ephem.h: where the James Webb Space Telescope is, one point a day.

Webb does not orbit the Earth. It circles the Sun-Earth L2 point, about 1.5 million km out,
so there are no two-line elements for it and SGP4 cannot place it. JPL's Horizons system
predicts its path several years ahead; this script asks Horizons for one geocentric
position a day (right ascension, declination, distance) and writes them as a table the
firmware interpolates. The Orb then needs no network at all for Webb.

Re-run it when the table is about to run out (the Satellites screen says so) or after a
large station-keeping change, then rebuild:

    python tools/gen_jwst_table.py [start YYYY-MM-DD] [stop YYYY-MM-DD]

Defaults: from the first of this month to 1 January four years on.
"""
import datetime
import re
import sys
import urllib.parse
import urllib.request

AU_KM = 149597870.7


def fetch(start, stop):
    q = {
        "format": "text", "COMMAND": "'-170'", "OBJ_DATA": "'NO'", "MAKE_EPHEM": "'YES'",
        "EPHEM_TYPE": "'OBSERVER'", "CENTER": "'500@399'", "START_TIME": f"'{start}'",
        "STOP_TIME": f"'{stop}'", "STEP_SIZE": "'1 d'", "QUANTITIES": "'1,20'",
        "ANG_FORMAT": "'DEG'", "CSV_FORMAT": "'YES'",
    }
    url = "https://ssd.jpl.nasa.gov/api/horizons.api?" + urllib.parse.urlencode(q)
    with urllib.request.urlopen(url, timeout=120) as r:
        text = r.read().decode()
    body = text.split("$$SOE")[1].split("$$EOE")[0]
    rows = []
    for line in body.strip().splitlines():
        f = [c.strip() for c in line.split(",")]
        # date, (solar presence), (lunar presence), RA deg, Dec deg, delta AU, deldot km/s
        date = datetime.datetime.strptime(f[0], "%Y-%b-%d %H:%M")
        nums = [c for c in f[1:] if re.fullmatch(r"-?\d+(\.\d+)?", c)]
        ra, dec, au = float(nums[0]), float(nums[1]), float(nums[2])
        rows.append((date, ra, dec, au * AU_KM))
    return rows


def main():
    today = datetime.date.today()
    start = sys.argv[1] if len(sys.argv) > 1 else today.replace(day=1).isoformat()
    stop = sys.argv[2] if len(sys.argv) > 2 else datetime.date(today.year + 4, 1, 1).isoformat()
    rows = fetch(start, stop)
    epoch = int(rows[0][0].replace(tzinfo=datetime.timezone.utc).timestamp())
    out = [
        "#pragma once",
        "// Generated by tools/gen_jwst_table.py from JPL Horizons (target -170, geocentric).",
        "// Do not edit; regenerate. One point a day, 00:00 UTC, starting at JWST_EPOCH.",
        "#include <stdint.h>",
        "",
        f"constexpr uint32_t JWST_EPOCH = {epoch}u;   // {rows[0][0]:%Y-%m-%d} 00:00 UTC",
        f"constexpr int      JWST_DAYS  = {len(rows)};      // last: {rows[-1][0]:%Y-%m-%d}",
        "",
        "// raHundredths: right ascension in 1/100 degree (0..35999)",
        "// decHundredths: declination in 1/100 degree",
        "// distThousandKm: distance from the Earth's centre in 1000 km",
        "struct JwstPoint { uint16_t raHundredths; int16_t decHundredths; uint16_t distThousandKm; };",
        "",
        "static const JwstPoint JWST_TABLE[JWST_DAYS] = {",
    ]
    for d, ra, dec, km in rows:
        out.append(f"    {{ {round(ra * 100) % 36000:5d}, {round(dec * 100):6d}, {round(km / 1000):5d} }},  // {d:%Y-%m-%d}")
    out.append("};")
    open("src/jwst_ephem.h", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print(f"{len(rows)} days, {rows[0][0]:%Y-%m-%d} .. {rows[-1][0]:%Y-%m-%d}")


if __name__ == "__main__":
    main()
